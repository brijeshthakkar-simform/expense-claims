// Builds staged Prisma schemas, generates Prisma's DDL per migration with `prisma migrate diff`,
// and assembles prisma/migrations folders + verified.sql (hand SQL prepended/appended).
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const ROOT = new URL('.', import.meta.url).pathname;
const OUT = join(ROOT, 'out');
const PRISMA = join(ROOT, 'node_modules/.bin/prisma');
const tpl = readFileSync(join(ROOT, 'schema/schema.template.prisma'), 'utf8');

function stage(n) {
  const out = [];
  let skipDepth = 0;
  for (const line of tpl.split('\n')) {
    const open = line.match(/^\s*\/\/ <s(\d)>\s*$/);
    const close = line.match(/^\s*\/\/ <\/s(\d)>\s*$/);
    if (open) { if (Number(open[1]) > n || skipDepth) skipDepth++; continue; }
    if (close) { if (skipDepth) skipDepth--; continue; }
    if (skipDepth) continue;
    const tag = line.match(/^(.*?)\s*\/\/ s(\d)\s*$/);
    if (tag) { if (Number(tag[2]) > n) continue; out.push(tag[1]); continue; }
    out.push(line);
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

function prisma(args, env = {}) {
  return execFileSync(PRISMA, args, { cwd: ROOT, env: { ...process.env, PRISMA_HIDE_UPDATE_MESSAGE: '1', ...env }, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'stages'), { recursive: true });
const stages = [1, 2, 3].map((n) => {
  const p = join(OUT, 'stages', `stage${n}.prisma`);
  writeFileSync(p, stage(n));
  process.stdout.write(prisma(['validate', '--schema', p]).split('\n').filter((l) => /valid/.test(l)).join('\n') + '\n');
  return p;
});
writeFileSync(join(OUT, 'schema.prisma'), readFileSync(stages[2], 'utf8'));

const diff = (from, to) => prisma(['migrate', 'diff', ...(from ? ['--from-schema', from] : ['--from-empty']), '--to-schema', to, '--script']);
const gen = { init: diff(null, stages[0]), workflow: diff(stages[0], stages[1]), receipts: diff(stages[1], stages[2]) };
const sql = (f) => readFileSync(join(ROOT, 'sql', f), 'utf8').trimEnd() + '\n';

const P = (name) => `PRISMA-GENERATED by \`pnpm prisma migrate dev --create-only --name ${name}\` (do not hand-write; shown so the reader sees what was verified)`;
const migrations = [
  { dir: '20261013090000_init', id: '0001_init', phase: 'P0', parts: [['HAND-WRITTEN: PREPEND above the Prisma DDL', sql('0001_init.pre.sql')], [P('init'), gen.init]] },
  { dir: '20261013091000_integrity_core', id: '0002_integrity_core', phase: 'P0', parts: [['HAND-WRITTEN (the Prisma-generated file is empty)', sql('0002_integrity_core.sql')]] },
  { dir: '20261013092000_privileges', id: '0003_privileges', phase: 'P0', parts: [['HAND-WRITTEN (the Prisma-generated file is empty)', sql('0003_privileges.sql')]] },
  { dir: '20261016090000_workflow', id: '0004_workflow', phase: 'P3', parts: [[P('workflow'), gen.workflow], ['HAND-WRITTEN: APPEND below the Prisma DDL', sql('0004_workflow.post.sql')]] },
  { dir: '20261021090000_receipts', id: '0005_receipts', phase: 'P6', parts: [[P('receipts'), gen.receipts], ['HAND-WRITTEN: APPEND below the Prisma DDL', sql('0005_receipts.post.sql')]] },
];

for (const [set, list] of [['migrations-p0', migrations.slice(0, 3)], ['migrations-full', migrations]]) {
  const base = join(OUT, set);
  mkdirSync(base, { recursive: true });
  writeFileSync(join(base, 'migration_lock.toml'), '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
  for (const m of list) {
    mkdirSync(join(base, m.dir), { recursive: true });
    writeFileSync(join(base, m.dir, 'migration.sql'), m.parts.map(([kind, body]) => `-- >>>> ${kind}\n${body.trimEnd()}\n`).join('\n'));
  }
}
writeFileSync(join(OUT, 'migrations.json'), JSON.stringify(migrations.map(({ dir, id, phase, parts }) => ({ dir, id, phase, parts: parts.map(([k]) => k) })), null, 2));
console.log('built', migrations.map((m) => m.dir).join(', '));

// Generate the Prisma client used by run.mjs's error-shape probe (PE group): probe-client/generated (gitignored).
execFileSync(PRISMA, ['generate', '--schema', 'probe-client/schema.prisma'], { cwd: ROOT, stdio: 'inherit' });
